"""Reads openapi.json and writes src/Astroway/Namespaces.g.cs.

Same naming rule as the Python and TypeScript SDKs: the operationId is split on `_` into
namespace and method parts, `-` separates words inside a part, a single-part operationId
gets `Compute`. So `vedic_dashas_vimshottari_maha` becomes aw.Vedic.DashasVimshottariMahaAsync.

Skipped: path templates (`/webhooks/{id}/test`), non-JSON answers (embeds, SSE streams) and
the `/public/*` mirrors. Every skipped path is still reachable through AstrowayClient.RequestAsync.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "openapi.json"
OUT = ROOT / "src" / "Astroway" / "Namespaces.g.cs"


def words(s: str) -> list[str]:
    return [w for w in (re.sub(r"[^a-zA-Z0-9]", "", p) for p in re.split(r"[-]+", s)) if w]


def camel(parts: list[str]) -> str:
    out = "".join(w[:1].upper() + w[1:].lower() for p in parts for w in words(p))
    return "N" + out if out[:1].isdigit() else out


def ascii_doc(s: str) -> str:
    table = {0x00D7: "x", 0x2014: "-", 0x2013: "-", 0x2018: "'", 0x2019: "'", 0x201C: '"', 0x201D: '"'}
    return s.translate(table).replace("\n", " ").strip()


def collect(spec: dict) -> dict[str, list[dict]]:
    by_ns: dict[str, list[dict]] = {}
    for path, methods in spec.get("paths", {}).items():
        op = methods.get("post") or methods.get("get")
        verb = "POST" if methods.get("post") else "GET"
        if not op or not op.get("operationId") or "{" in path or path.startswith("/public/"):
            continue
        ok = ((op.get("responses") or {}).get("200") or {}).get("content") or {}
        if "application/json" not in ok:
            continue
        parts = [p for p in (re.sub(r"[{}]", "", x) for x in op["operationId"].split("_")) if p]
        if not parts:
            continue
        ns = camel([parts[0]])
        method = "Compute" if len(parts) == 1 else camel(parts[1:])
        if not ns or not method:
            continue
        by_ns.setdefault(ns, []).append({"method": method, "path": path, "verb": verb, "summary": op.get("summary") or ""})
    return by_ns


def xml(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def main() -> int:
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    by_ns = collect(spec)
    bad = 0
    for ns, items in by_ns.items():
        seen: dict[str, str] = {}
        for it in items:
            if seen.get(it["method"], it["path"]) != it["path"]:
                print(f"collision: {ns}.{it['method']} -> {seen[it['method']]} vs {it['path']}", file=sys.stderr)
                bad += 1
            seen[it["method"]] = it["path"]
    if bad:
        return 1

    out = [
        "// <auto-generated>",
        f"// Generated by scripts/generate.py from openapi.json (API {spec['info']['version']}). Do not edit.",
        "// </auto-generated>",
        "#nullable enable",
        "using System.Net.Http;",
        "using System.Threading;",
        "using System.Threading.Tasks;",
        "",
        "namespace Astroway",
        "{",
        "    public sealed partial class AstrowayClient",
        "    {",
    ]
    for ns in sorted(by_ns):
        out.append(f"        /// <summary>The {ns} endpoints.</summary>")
        out.append(f"        public {ns}Namespace {ns} {{ get; private set; }} = null!;")
    out.append("")
    out.append("        private void InitNamespaces()")
    out.append("        {")
    for ns in sorted(by_ns):
        out.append(f"            {ns} = new {ns}Namespace(this);")
    out += ["        }", "    }", ""]
    for ns in sorted(by_ns):
        out += [
            f"    /// <summary>The {ns} endpoints.</summary>",
            f"    public sealed class {ns}Namespace",
            "    {",
            "        private readonly AstrowayClient _c;",
            f"        internal {ns}Namespace(AstrowayClient c) {{ _c = c; }}",
        ]
        for it in sorted(by_ns[ns], key=lambda x: x["method"]):
            doc = xml(ascii_doc(it["summary"]) or it["path"])
            out.append("")
            out.append(f"        /// <summary>{doc} ({it['verb']} {it['path']}).</summary>")
            if it["verb"] == "GET":
                out.append(f"        public Task<AstrowayResponse> {it['method']}Async(RequestOptions? options = null, CancellationToken cancellationToken = default)")
                out.append(f'            => _c.RequestAsync(HttpMethod.Get, "{it["path"]}", null, options, cancellationToken);')
            else:
                out.append(f"        public Task<AstrowayResponse> {it['method']}Async(object? body = null, RequestOptions? options = null, CancellationToken cancellationToken = default)")
                out.append(f'            => _c.RequestAsync(HttpMethod.Post, "{it["path"]}", body, options, cancellationToken);')
        out += ["    }", ""]
    out.append("}")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    n = sum(len(v) for v in by_ns.values())
    print(f"{len(by_ns)} namespaces, {n} methods -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
